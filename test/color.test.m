static int count = 0, failures = 0;

static void check(BOOL isPassed, NSString *message) {
	count++;
	if (!isPassed) {
		fprintf(stderr, "failed: %s\n", message.UTF8String);
		failures++;
	}
}

// What `css` serializes as, "" when it's no colour:
static void checkSerialized(NSString *css, NSString *expected) {
	NSString *serialized = [SGCSSColor parse:css].serialized ?: @"";
	check([serialized isEqualToString:expected], [NSString stringWithFormat:
			@"<%@>: <%@>, not <%@>", css, serialized, expected]);
}

static uint8_t byteOf(double component) {
	return (uint8_t)round(component * 255.0);
}

